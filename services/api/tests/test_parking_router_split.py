def test_every_former_module_name_is_still_importable():
    package = importlib.import_module(PKG)
    missing = [name for name in FORMER_MODULE_NAMES if not hasattr(package, name)]
    assert missing == []
    from services.api.app.routers.parking import LayoutRevisionStatus  # noqa: F401  (used by an existing test)


def test_route_groups_stay_in_original_registration_order():
    package = importlib.import_module(PKG)
    paths = [route.path for route in package.router.routes]
    assert paths[0] == "/api/v1/sites"
    assert paths.index("/api/v1/cameras/{camera_id}/layouts") < paths.index("/api/v1/cameras/{camera_id}/stability/assess")
    assert paths.index("/api/v1/cameras/{camera_id}/stability/assess") < paths.index("/api/v1/cameras/{camera_id}/occupancy/jobs")
    assert paths[-1] == "/api/v1/cameras/{camera_id}/capacity/snapshot"

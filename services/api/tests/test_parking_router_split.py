"""The parking router package keeps one router, the original route order and every old name."""
import importlib

PKG = "services.api.app.routers.parking"
SUBMODULES = ("_common", "sites_cameras", "layouts", "stability", "occupancy_jobs", "hazards_capacity")


def test_single_router_with_all_routes_registered_once():
    package = importlib.import_module(PKG)
    for name in SUBMODULES:
        assert importlib.import_module(f"{PKG}.{name}").router is package.router
    keys = [(route.path, tuple(sorted(route.methods))) for route in package.router.routes]
    assert len(keys) == 42 and len(set(keys)) == 42


